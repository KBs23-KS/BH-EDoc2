import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {signedPdfFileName} from "../src/signedPdfFileName.js";
assert.equal(signedPdfFileName("คำสั่งแต่งตั้งคณะกรรมการ.pdf"),"คำสั่งแต่งตั้งคณะกรรมการ (ลงนามแล้ว).pdf");
assert.equal(signedPdfFileName("ประกาศโรงเรียน.PDF"),"ประกาศโรงเรียน (ลงนามแล้ว).PDF");
assert.equal(signedPdfFileName("คำสั่ง (ลงนามแล้ว).pdf"),"คำสั่ง (ลงนามแล้ว).pdf");
assert.equal(signedPdfFileName("คำสั่ง (ลงนามแล้ว) (ลงนามแล้ว).pdf"),"คำสั่ง (ลงนามแล้ว).pdf");
assert.equal(signedPdfFileName(""),"เอกสาร (ลงนามแล้ว).pdf");
assert.equal(signedPdfFileName(undefined,"เอกสาร-1"),"เอกสาร-1 (ลงนามแล้ว).pdf");
assert.equal(signedPdfFileName("../bad/name.pdf"),".._bad_name (ลงนามแล้ว).pdf");
assert.equal(signedPdfFileName("รายงานฉบับที่ 1.pdf"),"รายงานฉบับที่ 1 (ลงนามแล้ว).pdf");
const editor=readFileSync(new URL("../src/PdfSignatureEditor.jsx",import.meta.url),"utf8");
const app=readFileSync(new URL("../src/App.jsx",import.meta.url),"utf8");
assert.ok(editor.includes("signedPdfFileName(original?.name,"),"Signed file names derive from stored source file name");
assert.ok(!editor.includes("signed-${document.docNumber"),"Old generated number-name pattern removed");
assert.ok(editor.includes("new File([bytes]"),"PDF bytes still saved as File");
assert.ok(editor.includes("onSubmit(next)"),"Signing approval unchanged");
assert.ok(app.includes("uploadFileToGoogleDrive(originals[i])"),"Uploaded PDF retains File.name");
assert.ok(app.includes('const [rememberUsername,setRememberUsername] = useState('),"Explicit opt-in remember choice");
assert.ok(app.includes('type="checkbox"'),"Login opt-in checkbox");
assert.ok(app.includes('autoComplete="current-password"'),"Password manager remains supported");
assert.ok(!app.includes("localStorage.setItem(LOGIN_USERNAME_STORAGE_KEY,password)"),"Password never persisted");
assert.ok(app.includes("localStorage.setItem(LOGIN_USERNAME_STORAGE_KEY,username.trim())"),"Username persisted only after successful login");
assert.ok(app.includes('localStorage.removeItem(LOGIN_USERNAME_STORAGE_KEY)'),"Opt-out clears remembered username");
assert.ok(app.includes("setUsername(rememberUsername?readRememberedUsername():\"\")"),"Logout leaves remembered username");
console.log("Signed PDF original-name and remembered username regression passed");
