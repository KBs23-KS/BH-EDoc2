import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {readLocalSignaturePdf,signaturePdfNamesMatch} from "../src/signatureLocalPdf.js";
const b=new TextEncoder().encode("%PDF-1.7\\n1 0 obj\\n");
const mock={name:"คำสั่งโรงเรียน.pdf",size:b.byteLength,arrayBuffer:async()=>b.buffer.slice(0)};
assert.deepEqual(await readLocalSignaturePdf(mock),b);
assert.equal(signaturePdfNamesMatch("คำสั่งโรงเรียน (1).pdf","คำสั่งโรงเรียน.pdf"),true);
assert.equal(signaturePdfNamesMatch("wrong.pdf","คำสั่งโรงเรียน.pdf"),false);
await assert.rejects(()=>readLocalSignaturePdf({...mock,name:"evil.txt"}),/PDF/);
await assert.rejects(()=>readLocalSignaturePdf({...mock,size:0}),/ว่างเปล่า/);
await assert.rejects(()=>readLocalSignaturePdf({...mock,size:101*1024*1024}),/100 MB/);
const wrong=new TextEncoder().encode("Not a PDF");
await assert.rejects(()=>readLocalSignaturePdf({...mock,size:wrong.byteLength,arrayBuffer:async()=>wrong.buffer.slice(0)}),/ไม่ใช่ PDF/);
const editor=readFileSync(new URL("../src/PdfSignatureEditor.jsx",import.meta.url),"utf8");
const gas=readFileSync(new URL("../gas/Code.gs",import.meta.url),"utf8");
assert.ok(editor.includes("loadFromDevice"));
assert.ok(editor.includes("readLocalSignaturePdf(file)"));
assert.ok(editor.includes('!sourceBytes} onClick={saveCurrent}'));
assert.ok(editor.includes('sourceFiles[fileIndex].driveId'));
assert.ok(editor.includes('onSubmit(next)'),"Signed PDFs still go through original approval pipeline");
assert.ok(!editor.includes('backupSecret:'),"PDF signer must not embed Backup credentials");
assert.ok(gas.includes('data.action === "getFile"'),"Backup API security remains intact");
console.log("BHS PDF signer local-source fallback regression checks passed");
