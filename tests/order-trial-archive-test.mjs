import assert from "node:assert/strict";
import {canArchiveTrialOrder,canRestoreTrialOrder} from "../src/orderTrialArchive.js";
const order={id:"ORDER-2569-1",orderNumber:"1/2569",status:"linked",linkedDocumentId:"DOC-1"};
const doc={id:"DOC-1",reservationId:order.id,docNumber:order.orderNumber,type:"คำสั่งโรงเรียน",status:"รอรองผู้อำนวยการ",files:[{driveId:"real-file"}]};
assert.equal(canArchiveTrialOrder(order,doc),"");
assert.equal(canArchiveTrialOrder({...order,linkedDocumentId:undefined},null),"");
assert.match(canArchiveTrialOrder(order,null),/ไม่พบเอกสาร/);
assert.match(canArchiveTrialOrder(order,{...doc,docNumber:"2/2569"}),/ไม่ตรงกัน/);
assert.match(canArchiveTrialOrder(order,{...doc,status:"เผยแพร่แล้ว"}),/ผ่านขั้นตอน/);
assert.match(canArchiveTrialOrder(order,{...doc,status:"อนุมัติ\/สั่งการแล้ว"}),/ผ่านขั้นตอน/);
assert.match(canArchiveTrialOrder(order,{...doc,signedFiles:[{}]}),/ลงนาม/);
assert.match(canArchiveTrialOrder(order,{...doc,acknowledgedBy:["teacher"]}),/ลงนาม/);
assert.match(canArchiveTrialOrder(order,{...doc,routingEntries:[{}]}),/ลงนาม/);
assert.match(canArchiveTrialOrder(order,{...doc,isDeleted:true}),/ถังขยะ/);
assert.match(canArchiveTrialOrder({...order,status:"canceled"},null),/ยกเลิก/);
const archived={...order,trialArchived:true},archivedDoc={...doc,isDeleted:true,trialArchived:true};
assert.equal(canRestoreTrialOrder(archived,archivedDoc),"");
assert.equal(canRestoreTrialOrder({...archived,linkedDocumentId:undefined},null),"");
assert.match(canRestoreTrialOrder(archived,{...doc,isDeleted:false}),/สถานะ/);
assert.match(canRestoreTrialOrder({...archived,linkedDocumentId:"DOC-2"},archivedDoc),/ไม่ตรงกัน/);
assert.match(canRestoreTrialOrder(archived,{...archivedDoc,status:"เผยแพร่แล้ว"}),/ไม่อนุญาต/);
console.log("Reversible trial order archive safety rules passed");
